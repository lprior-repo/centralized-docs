//! `ctd-mcp` - Standalone MCP server binary for AI agent integration
//!
//! This binary provides a standalone MCP (Model Context Protocol) server
//! that wraps the documentation search functionality for AI agents.

use std::path::PathBuf;

use anyhow::Result;
use tracing::instrument;

fn print_usage(program: &str) {
    eprintln!(
        "ctd-mcp v{} - MCP server for documentation search",
        env!("CARGO_PKG_VERSION")
    );
    eprintln!();
    eprintln!("Usage:");
    eprintln!("  {program} <INDEX_DIR>    Start the MCP server");
    eprintln!();
    eprintln!("Options:");
    eprintln!("  -h, --help      Show this help message");
    eprintln!("  -V, --version   Show version information");
    eprintln!();
    eprintln!("INDEX_DIR must contain an INDEX.json file generated by `ctd index`.");
}

#[tokio::main]
#[instrument]
async fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    let program = args
        .first()
        .map(std::string::String::as_str)
        .map_or("ctd-mcp", |s| s);

    if args.iter().any(|a| a == "--help" || a == "-h") {
        print_usage(program);
        std::process::exit(0);
    }

    if args.iter().any(|a| a == "--version" || a == "-V") {
        eprintln!("ctd-mcp v{}", env!("CARGO_PKG_VERSION"));
        std::process::exit(0);
    }

    let index_dir = args.get(1).map(PathBuf::from).ok_or_else(|| {
        anyhow::anyhow!(
            "Usage: ctd-mcp <INDEX_DIR>\n\
                 \n\
                 Start the ctd MCP server for documentation search.\n\
                 \n\
                 INDEX_DIR must contain an INDEX.json file generated by `ctd index`."
        )
    })?;

    doc_transformer::mcp::run_mcp_serve(&index_dir).await
}
